SELECT * FROM "Н_ЛЮДИ" INNER JOIN
    ("Н_УЧЕНИКИ" INNER JOIN
        (SELECT "Н_ПЛАНЫ"."ИД" AS "ИД_ПЛАНЫ", "Н_ПЛАНЫ"."ОТД_ИД" FROM "Н_ОТДЕЛЫ" INNER JOIN "Н_ПЛАНЫ"
            ON "Н_ОТДЕЛЫ"."КОРОТКОЕ_ИМЯ" = 'КТиУ' AND "Н_ПЛАНЫ"."ОТД_ИД" = "Н_ОТДЕЛЫ"."ИД") as a
    ON a."ИД_ПЛАНЫ" = "Н_УЧЕНИКИ"."ПЛАН_ИД" AND "ПРИЗНАК" <> 'диплом' AND "ПРИЗНАК" <> 'отчисл') AS b
ON b."ЧЛВК_ИД" = "Н_ЛЮДИ"."ИД" WHERE date_part('year', age("ДАТА_РОЖДЕНИЯ")) > 25;
