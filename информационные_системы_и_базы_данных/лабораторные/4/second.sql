SELECT "Н_ЛЮДИ"."ИМЯ", "Н_ВЕДОМОСТИ"."ДАТА", "Н_СЕССИЯ"."ЧЛВК_ИД" FROM "Н_ЛЮДИ"
    LEFT JOIN "Н_ВЕДОМОСТИ"
    ON "Н_ЛЮДИ"."ИД" = "Н_ВЕДОМОСТИ"."ЧЛВК_ИД"
        LEFT JOIN "Н_СЕССИЯ"
        ON "Н_ЛЮДИ"."ИД" = "Н_СЕССИЯ"."ЧЛВК_ИД"
WHERE
    "Н_ЛЮДИ"."ИМЯ" > 'Николай' AND "Н_ВЕДОМОСТИ"."ИД" < 1250972;